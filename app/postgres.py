"""Neon PostgreSQL 연결과 초기화. 접속 정보는 DATABASE_URL로만 받습니다."""
from datetime import date
import psycopg

# 모든 서버 인스턴스가 같은 잠금을 사용해 초기화·정원 검사·저장을 순서대로 처리합니다.
TRANSACTION_LOCK = 739214605

POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS classroom (
    guild_id TEXT PRIMARY KEY,
    class_number INTEGER UNIQUE NOT NULL CHECK(class_number > 0),
    total_students INTEGER NOT NULL CHECK(total_students > 0)
);
CREATE TABLE IF NOT EXISTS movement (
    movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id TEXT NOT NULL REFERENCES classroom(guild_id),
    student_number TEXT NOT NULL,
    student_name TEXT NOT NULL,
    move_date DATE NOT NULL,
    period INTEGER NOT NULL CHECK(period > 0),
    place TEXT NOT NULL,
    registration_id BIGINT NOT NULL,
    period_string TEXT NOT NULL,
    UNIQUE(guild_id, student_number, move_date, period)
);
CREATE INDEX IF NOT EXISTS idx_movement_current ON movement(guild_id, move_date, period);
CREATE INDEX IF NOT EXISTS idx_movement_registration ON movement(registration_id);
CREATE TABLE IF NOT EXISTS analog_count (
    guild_id TEXT NOT NULL REFERENCES classroom(guild_id),
    count_date DATE NOT NULL,
    analog_count INTEGER NOT NULL DEFAULT 0 CHECK(analog_count >= 0),
    PRIMARY KEY(guild_id, count_date)
);
CREATE TABLE IF NOT EXISTS metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE OR REPLACE VIEW movement_ranges AS
    SELECT registration_id AS id, guild_id, student_number, student_name AS name,
           MIN(period) AS start_period, MAX(period) AS end_period,
           period_string, place, move_date AS day
    FROM movement
    GROUP BY registration_id, guild_id, student_number, student_name,
             period_string, place, move_date
"""


class DatabaseRow(dict):
    # 기존 코드에서 열 이름과 열 번호로 읽는 방식을 모두 지원합니다.
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def row_factory(cursor):
    names = [column.name for column in cursor.description or []]

    def make_row(values):
        return DatabaseRow({
            name: value.isoformat() if isinstance(value, date) else value
            for name, value in zip(names, values)
        })

    return make_row


class PostgresConnection:
    """기존 매개변수 SQL을 psycopg 형식으로 전달하는 공통 연결 인터페이스입니다."""
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, params=None):
        # SQL 값은 문자열에 직접 붙이지 않고 드라이버에 별도 매개변수로 전달합니다.
        return self.connection.execute(query.replace("?", "%s"), params)

    def executemany(self, query, rows):
        cursor = self.connection.cursor()
        cursor.executemany(query.replace("?", "%s"), rows)
        return cursor


def connect(database_url):
    # 요청 후 연결을 닫아 서버리스 재사용 시 끊어진 연결을 재사용하지 않습니다.
    return psycopg.connect(
        database_url, connect_timeout=10, prepare_threshold=None,
        row_factory=row_factory,
    )


def lock_transaction(db):
    db.execute("SET LOCAL lock_timeout = '10s'")
    db.execute("SET LOCAL statement_timeout = '15s'")
    db.execute("SELECT pg_advisory_xact_lock(?)", (TRANSACTION_LOCK,))


def initialize_postgres(db):
    lock_transaction(db)
    for statement in POSTGRES_SCHEMA.split(";"):
        if statement.strip():
            db.execute(statement)
